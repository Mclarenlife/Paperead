import { test, expect } from '@playwright/test'

test('neutral workspace with accents, persistent sidebar and document tabs', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.paper-card')).toHaveCount(6)
  await expect(page.locator('.welcome')).toHaveCount(0)
  await expect(page.getByRole('tab', { name: '文献库', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '收起侧栏', exact: true }).click()
  await expect(page.locator('.sidebar')).toHaveCSS('width', '64px')
  await page.reload()
  await expect(page.getByRole('button', { name: '展开侧栏', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click()
  const first = await page.locator('.paper-title').first().textContent()
  await page.locator('.paper-title').first().click()
  await expect(page.getByRole('region', { name: '文献阅读器' })).toBeVisible()
  await page.getByRole('tab', { name: '文献库', exact: true }).click()
  await expect(page.getByRole('region', { name: '文献阅读器' })).toHaveCount(0)
  await page.locator('.paper-title').nth(1).click()
  await expect(page.locator('.document-tab')).toHaveCount(2)
  await page.getByRole('tab', { name: first!.trim(), exact: true }).click()
  await expect(page.locator('.reader-heading strong')).toHaveText(first!.trim())
  await expect(page.locator('.reader-overlay')).toHaveCSS('opacity', '1')
  await page.screenshot({ path: '.tmp/redesign-reader.png' })
  await page.locator('.document-tab.active .tab-close').click()
  await expect(page.locator('.document-tab')).toHaveCount(1)
  await page.getByRole('tab', { name: '文献库', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.scrollX)).toBe(0)
  await page.screenshot({
    path: '.tmp/redesign-library.png',
    fullPage: true,
    animations: 'disabled',
  })
  const colors = await page.evaluate(() => {
    const style = getComputedStyle(document.documentElement)
    return ['--accent', '--success', '--danger'].map((name) => style.getPropertyValue(name).trim())
  })
  expect(colors).toEqual(['#0d74ce', '#18794e', '#ce2c31'])
  await page.getByRole('button', { name: '偏好设置', exact: true }).click()
  await page.getByRole('button', { name: '外观', exact: true }).click()
  await page.getByRole('button', { name: '夜读', exact: true }).click()
  await page.getByRole('button', { name: '关闭', exact: true }).click()
  await expect(page.locator('html')).toHaveCSS('background-color', 'rgb(17, 17, 17)')
  await page.screenshot({ path: '.tmp/redesign-dark.png', animations: 'disabled' })
})

